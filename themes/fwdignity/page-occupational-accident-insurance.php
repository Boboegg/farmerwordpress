  <!-- FAQ -->
  <section class="es-sec reveal">
    <div class="es-sec-head">
      <span class="kicker">FAQ · 常見問題</span>
      <h2>常見<span class="accent">問答</span></h2>
      <p>精選自農業部官方 FAQ，點擊展開答案。</p>
    </div>
    <div class="es-faq">
      <details class="es-faq-item">
        <summary>Q1：加保有沒有年齡上限？</summary>
        <div class="answer">沒有。只要實際從事農業工作且符合申請資格即可。<span class="source">（MOA, n.d., FAQ 問 5）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q2：我已經領老農津貼了，還能保嗎？</summary>
        <div class="answer">可以。不論是否已申領老農津貼，只要實際從事農業工作且具農保資格，都可以申請。<span class="source">（MOA, n.d., FAQ 問 9）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q3：在別人的農地幫忙受傷，也有給付嗎？</summary>
        <div class="answer">有。農職保保障範圍依兩大要件：地點在「田間」、行為是「農業工作」。不論自有或他人農地都受保障。<span class="source">（MOA, n.d., FAQ 問 18）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q4：長期務農的腰椎間盤突出算不算職業病？</summary>
        <div class="answer">農職保列舉的職業病包含「長期壓迫引發之關節滑囊病變」和「手指骨關節炎」等。如不在列舉項目內，可到農業部認可醫療機構找職業醫學科專科醫師評估。若醫師認定與農業工作有因果關係，也可視為職業病。<span class="source">（MOA, n.d., FAQ 問 20）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q5：農保和農職保可以同時領嗎？</summary>
        <div class="answer">不行，兩項保險僅得擇一。如果受傷原因是從農造成的，就申請農職保（金額較高）。<span class="source">（MOA, n.d., FAQ 問 21）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q6：我目前受傷在家休養，可以現在去加保嗎？</summary>
        <div class="answer">不行。農職保要求「實際從事農業工作」才符合加保資格。目前因傷病休養中不能從事農業工作者，不符加保及給付資格。<span class="source">（MOA, n.d., FAQ 問 10）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q7：112 年 12 月以後新加農保的人是自動加入農職保嗎？</summary>
        <div class="answer">是。自 112 年 12 月 1 日起，申請參加農保者視為一併申請參加農職保，只需填具農保申請表即可。<span class="source">（MOA, n.d., FAQ 問 6）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q8：怎麼證明受傷是因為農業工作？</summary>
        <div class="answer">按照申請書表提示填寫工作時間、地點、工作內容、受傷原因等。勞保局依提供資訊進行審查，有疑問可洽農會或勞保局。<span class="source">（MOA, n.d., FAQ 問 23）</span></div>
      </details>
    </div>
  </section>

