        <h3>職災隱形化</h3>
        <p>農民非勞動基準法適用對象，職業災害缺乏完整通報機制。近年曾發生中壯年農民高溫田間猝死、到院前缺乏完整醫學檢驗數據、職災認定困難致遺屬權益受損之案例（案例改編，身分資訊已去識別）。此類隱形化正是制度亟需改革之處。</p>
