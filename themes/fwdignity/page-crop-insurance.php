      <p>答案整理自農業金融署與 TAIF 公開資訊（BOAF, n.d.；TAIF, n.d.）。正式以官方最新規定為準。</p>
    </div>
    <div class="es-faq">
      <details class="es-faq-item">
        <summary>Q1：我已經有農保了，還需要投保農作物保險嗎？</summary>
        <div class="answer">需要。農保（農民健康保險）保障的是<strong>人</strong>——農民本人的生育、身心障礙、喪葬；農作物保險保障的是<strong>作物</strong>——天災或市場風險造成的農損。兩者目的不同、互補而非替代。<span class="source">（BOAF, n.d.；勞動部勞工保險局 [BLI], 2024）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q2：我租地耕種，可以投保嗎？</summary>
        <div class="answer">可以。只要實際從事農業生產、作物屬已開辦品項，租地耕種之農民亦可投保。具體要件（如農地證明、租約）依各保單條款辦理，請洽戶籍所在地或土地所在地農會。<span class="source">（BOAF, n.d.）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q3：理賠和天災救助可以同時領嗎？</summary>
        <div class="answer">可以。農業保險理賠與政府天災現金救助<strong>互不排斥</strong>，投保後遇天災可同時申請兩項。天災救助依農業部公告辦理；保險理賠依保單條款啟動。<span class="source">（MOA, n.d.；BOAF, n.d.）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q4：我的作物不在已開辦品項裡面怎麼辦？</summary>
        <div class="answer">目前已開辦 28 品項，政府正逐年擴大品項範圍。若你的作物尚未列入，可持續關注農業金融署公告，或向戶籍所在地農會反映需求以利納入未來規劃。<span class="source">（BOAF, n.d.）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q5：投保後沒有發生天災，保費會退嗎？</summary>
        <div class="answer">不退。保險的本質是「風險移轉」，繳納保費是購買未發生天災時的「保障狀態」。未發生事故不代表保險無效，而是代表你該年未觸發理賠條件。<span class="source">（保險業監理一般原則，來源待確認）</span></div>
      </details>
      <details class="es-faq-item">
        <summary>Q6：理賠大概要多久才能拿到錢？</summary>
        <div class="answer">視保單類型而定：<strong>天氣參數型</strong>最快約 <strong>15 天</strong>撥款（免勘災、達標即理賠）；<strong>實損實賠型</strong>需現場勘查，時間較長（依案件複雜度數週至數月）；<strong>收入保障型</strong>依年度結算時程。<span class="source">（TAIF, n.d.；BOAF, n.d.）</span></div>
      </details>
    </div>
  </section>

